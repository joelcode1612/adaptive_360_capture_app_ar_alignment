import 'package:adaptive_360_capture_app/features/virtual_tour/domain/models/virtual_tour.dart';

/// Reports how many of a tour's photographs the backend has accepted.
///
/// A count rather than a percentage: `package:http` gives no per-request
/// progress, and the server accepts one capture at a time, so the only honest
/// number is "n of m accepted".
typedef VirtualTourUploadProgress = void Function(int uploaded, int total);

/// The virtual-tour feature's needs from the outside world.
///
/// Three operations, mirroring the three write paths of the SiteSense API plus
/// the read that keeps the app honest about them. The Bloc is written against
/// this interface rather than against HTTP or a database, so the create →
/// upload → finalise lifecycle and its failure paths are testable without a
/// device, a server or a socket.
///
/// The seam below it is `VirtualTourRemoteDataSource` (the four FastAPI routes)
/// and `VirtualTourLocalDataSource` (the device's two JSON tables). Every
/// method returns the backend's own `TourResponse` as a [VirtualTourTicket];
/// none of them returns a panorama, because at this stage of the pipeline no
/// panorama exists — the manifest is the last verifiable artifact.
abstract class VirtualTourRepository {
  /// Creates the backend session if this local tour does not have one, uploads
  /// every capture into it, and records each acceptance.
  ///
  /// [tourId] is the app's local id; the backend's UUID is generated by the
  /// first call and stored, so a retry or a resumed session reuses it instead
  /// of filing a second tour. [captures] carry the 1-based `targetIndex` the
  /// server keys and orders by. Throws [VirtualTourFailure] with a message fit
  /// for the user.
  Future<VirtualTourTicket> uploadCaptures({
    required String tourId,
    required String propertyId,
    required String stationId,
    required List<TourCapture> captures,
    VirtualTourUploadProgress? onProgress,
  });

  /// Asks the backend to validate the capture count and write the stitch
  /// manifest. Returns the ticket in whatever status the server reports —
  /// normally `stitch_pending`, which is "awaiting stitching", not "done".
  Future<VirtualTourTicket> finaliseTour({required String tourId});

  /// Re-reads the server's state for a tour and stores it locally.
  Future<VirtualTourTicket> refreshTourStatus({required String tourId});

  /// The device's own record of a tour, including whether it ever reached a
  /// backend. Used to redraw the screen without asking the network.
  Future<VirtualTourRecord?> tourRecord(String tourId);
}
